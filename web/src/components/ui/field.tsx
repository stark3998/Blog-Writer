import { CircleAlert } from 'lucide-react';
import { Slot } from 'radix-ui';
import { useId, type ReactElement, type ReactNode } from 'react';

import { cn } from '@/lib/cn';

import { Label } from './label';

/** The props a `Field` wires onto its control. */
export interface FieldControlProps {
  id: string;
  'aria-describedby'?: string;
  'aria-invalid'?: true;
  'aria-required'?: true;
}

/** The props a `Fieldset` wires onto a group control (a `RadioGroup`, a `SegmentedControl`). */
export interface FieldGroupProps {
  'aria-labelledby': string;
  'aria-describedby'?: string;
  'aria-invalid'?: true;
  'aria-required'?: true;
}

function hasContent(node: ReactNode): boolean {
  return node !== undefined && node !== null && node !== false && node !== '';
}

function joinIds(...ids: (string | false)[]): string | undefined {
  const joined = ids.filter(Boolean).join(' ');
  return joined === '' ? undefined : joined;
}

function Message({ id, children }: { id: string; children: ReactNode }) {
  return (
    <p id={id} data-slot="field-error" className="flex items-start gap-1.5 text-sm font-medium text-danger">
      <CircleAlert aria-hidden="true" className="mt-0.5 size-4 shrink-0" />
      <span>{children}</span>
    </p>
  );
}

function Description({ id, children }: { id: string; children: ReactNode }) {
  return (
    <div id={id} data-slot="field-description" className="text-sm text-ink-muted">
      {children}
    </div>
  );
}

function RequiredMark() {
  // `aria-required` on the control says it to screen readers; this says it to everyone else.
  return (
    <span aria-hidden="true" className="ml-1 font-normal text-ink-subtle">
      (required)
    </span>
  );
}

export interface FieldProps {
  label: ReactNode;
  /** A hint before the control: format, limits, where the value goes. */
  description?: ReactNode;
  /** The error message; when set, the control is `aria-invalid` and described by it. */
  error?: ReactNode;
  required?: boolean;
  /** `horizontal` puts a checkbox or switch before its label, in a row that is a 44 px target on touch screens. */
  orientation?: 'vertical' | 'horizontal';
  /** Keeps the label for screen readers only, when the context already shows it. */
  hideLabel?: boolean;
  /** The control's id (generated by default). Set it here, never on the control. */
  id?: string;
  className?: string;
  /**
   * The control: an element (`<Input />`, `<Textarea />`, `<Switch />`, `<Checkbox />`) that gets
   * `id`, `aria-describedby`, `aria-invalid` and `aria-required`; or a function that receives those
   * props, for composite controls (`<Select>` puts them on its `SelectTrigger`).
   */
  children: ReactElement | ((control: FieldControlProps) => ReactNode);
}

/**
 * A labelled form control with its hint and error message, wired for assistive technology.
 *
 * ```tsx
 * <Field label="Post URL" description="Copy it from the post’s menu on LinkedIn." error={errors.url} required>
 *   <Input type="url" value={url} onChange={…} />
 * </Field>
 * ```
 */
export function Field({
  label,
  description,
  error,
  required = false,
  orientation = 'vertical',
  hideLabel = false,
  id,
  className,
  children,
}: FieldProps) {
  const baseId = useId();
  const controlId = id ?? `${baseId}control`;
  const descriptionId = `${baseId}description`;
  const errorId = `${baseId}error`;
  const invalid = hasContent(error);
  const described = hasContent(description);
  const control: FieldControlProps = {
    id: controlId,
    'aria-describedby': joinIds(described && descriptionId, invalid && errorId),
    ...(invalid ? { 'aria-invalid': true as const } : {}),
    ...(required ? { 'aria-required': true as const } : {}),
  };
  const rendered = typeof children === 'function' ? children(control) : <Slot.Root {...control}>{children}</Slot.Root>;
  const labelNode = (
    <Label htmlFor={controlId} className={cn(hideLabel && 'sr-only')}>
      {label}
      {required ? <RequiredMark /> : null}
    </Label>
  );

  if (orientation === 'horizontal') {
    return (
      <div
        data-slot="field"
        data-orientation="horizontal"
        data-invalid={invalid || undefined}
        className={cn('flex items-start gap-3', className)}
      >
        <div className="flex h-5.5 shrink-0 items-center pointer-coarse:h-11">{rendered}</div>
        <div className="grid min-w-0 gap-1">
          <div className="flex min-h-5.5 items-center pointer-coarse:min-h-11">{labelNode}</div>
          {described ? <Description id={descriptionId}>{description}</Description> : null}
          {invalid ? <Message id={errorId}>{error}</Message> : null}
        </div>
      </div>
    );
  }

  return (
    <div data-slot="field" data-invalid={invalid || undefined} className={cn('grid gap-1.5', className)}>
      {labelNode}
      {described ? <Description id={descriptionId}>{description}</Description> : null}
      {rendered}
      {invalid ? <Message id={errorId}>{error}</Message> : null}
    </div>
  );
}

export interface FieldsetProps {
  /** Names the group, like a label names one control. */
  legend: ReactNode;
  description?: ReactNode;
  error?: ReactNode;
  required?: boolean;
  hideLegend?: boolean;
  className?: string;
  /**
   * Several `Field`s (checkboxes), or a function that receives the group props for a single group
   * control: `{(group) => <RadioGroup {...group}>…</RadioGroup>}`.
   */
  children: ReactNode | ((group: FieldGroupProps) => ReactNode);
}

/** A group of controls that answer one question ("Which pillars?", "Mode for this week"). */
export function Fieldset({
  legend,
  description,
  error,
  required = false,
  hideLegend = false,
  className,
  children,
}: FieldsetProps) {
  const baseId = useId();
  const legendId = `${baseId}legend`;
  const descriptionId = `${baseId}description`;
  const errorId = `${baseId}error`;
  const invalid = hasContent(error);
  const described = hasContent(description);
  const describedBy = joinIds(described && descriptionId, invalid && errorId);
  const group: FieldGroupProps = {
    'aria-labelledby': legendId,
    'aria-describedby': describedBy,
    ...(invalid ? { 'aria-invalid': true as const } : {}),
    ...(required ? { 'aria-required': true as const } : {}),
  };
  return (
    <fieldset
      data-slot="fieldset"
      data-invalid={invalid || undefined}
      aria-describedby={describedBy}
      className={cn('m-0 min-w-0 border-0 p-0', className)}
    >
      <legend id={legendId} className={cn('mb-1.5 p-0 text-sm font-medium text-ink', hideLegend && 'sr-only')}>
        {legend}
        {required ? <RequiredMark /> : null}
      </legend>
      <div className="grid gap-3">
        {described ? <Description id={descriptionId}>{description}</Description> : null}
        {typeof children === 'function' ? children(group) : children}
        {invalid ? <Message id={errorId}>{error}</Message> : null}
      </div>
    </fieldset>
  );
}

/** Moves focus to the first invalid control inside `container`, after a submit that failed. */
export function focusFirstInvalid(container: ParentNode | null): boolean {
  const target = container?.querySelector<HTMLElement>('[aria-invalid="true"]');
  if (!target) return false;
  target.focus();
  return true;
}
